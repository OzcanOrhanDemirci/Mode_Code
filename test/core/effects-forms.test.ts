/**
 * Every form the classifier knows, with what it answers, reviewed one by one: each line is a program, its
 * class and why, the files it writes ([…], ? for one only known at run time) and the folder it runs in when
 * that is not the session's (@…, ? when a cd made it unknown). A change to any answer must be deliberate.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { commandEffects, type EffectEnv } from '../../src/core/shell/effects.js';

const LINUX: EffectEnv = { platform: 'linux', home: '/h', cwd: '/p', env: { TMPDIR: '/tmp', X: '/x' } };
const WIN: EffectEnv = { platform: 'win32', home: 'C:/U', cwd: 'C:/p', env: { TEMP: 'C:/U/T' } };

function show(cmd: string, dialect: 'bash' | 'powershell', env: EffectEnv): string {
  return commandEffects(cmd, dialect, env)
    .effects.map(
      (e) =>
        `${e.program}:${e.kind}/${e.why}${e.targets.length ? `[${e.targets.map((t) => t ?? '?').join(',')}]` : ''}${e.cwd !== env.cwd ? `@${e.cwd ?? '?'}` : ''}`,
    )
    .join(' ');
}

